/**
 * Static zh lookup for transport/adapter helpers invoked without a live
 * locale seat (tests, headless callers). Live callers pass the runtime `t`.
 * @param key - sidebar dictionary key.
 * @param params - optional `{name}` template values.
 * @returns the zh text with placeholders replaced.
 */
export function zhTranslate(key: SidebarKey, params?: Record<string, unknown>): string {
  let text: string = zh[key]
  for (const [name, value] of Object.entries(params ?? {})) {
    text = text.split(`{${name}}`).join(String(value))
  }
  return text
}
